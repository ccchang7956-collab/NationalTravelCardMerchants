def random_jitter(center_lat: float, center_lon: float, radius_km: float) -> tuple[float, float]:
    """在區域中心點附近隨機散佈，使用均勻隨機角度 + 隨機半徑。"""
    r_km = random.uniform(0, radius_km * 0.8)  # 使用 80% 半徑，避免跑到邊界
    angle = random.uniform(0, 2 * math.pi)
    
    # 1 度緯度 ≈ 111 km
    dlat = (r_km / 111.0) * math.cos(angle)
    # 1 度經度隨緯度不同
    dlon = (r_km / (111.0 * math.cos(math.radians(center_lat)))) * math.sin(angle)
    
    return center_lat + dlat, center_lon + dlon


def main():
    random.seed(42)  # 固定隨機種子確保可重現性
    
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    cursor = conn.cursor()

    # Ensure lat/lon columns exist
    for col in ["lat", "lon"]:
        try:
            cursor.execute(f"ALTER TABLE merchants ADD COLUMN {col} REAL")
            conn.commit()
        except sqlite3.OperationalError:
            pass

    # Clear previous (wrong) coordinates
    cursor.execute("UPDATE merchants SET lat = NULL, lon = NULL")
    conn.commit()

    # Fetch all merchants with zip codes
    cursor.execute("""
        SELECT id, zip_code FROM merchants
        WHERE zip_code IS NOT NULL AND zip_code != ''
    """)
    merchants = cursor.fetchall()

    updated = 0
    skipped = 0
    missing_zips = set()

    print(f"Processing {len(merchants)} merchants...")

    batch = []
    for m in merchants:
        zip_key = str(m["zip_code"]).strip()[:3]
        entry = TAIWAN_ZIPCODES.get(zip_key)
        if entry:
            clat, clon, radius = entry
            lat, lon = random_jitter(clat, clon, radius)
            batch.append((lat, lon, m["id"]))
            updated += 1
        else:
            missing_zips.add(zip_key)
            skipped += 1

    cursor.executemany(
        "UPDATE merchants SET lat = ?, lon = ? WHERE id = ?",
        batch
    )
    conn.commit()

    cursor.execute("SELECT COUNT(*) FROM merchants WHERE lat IS NOT NULL")
    total_geocoded = cursor.fetchone()[0]
    cursor.execute("SELECT COUNT(*) FROM merchants")
    total = cursor.fetchone()[0]

    print(f"\n✅ 座標更新完成！")
    print(f"   {total_geocoded}/{total} 間商店已有座標 ({total_geocoded/total*100:.1f}%)")
    print(f"   每間商店在行政區內隨機散佈，不再堆疊在同一點")
    if missing_zips:
        print(f"   未找到對應郵遞區號：{sorted(missing_zips)}")

    conn.close()


if __name__ == "__main__":
    main()
