_GROUP_BY_PREFIX = {
    prefix: (code, name)
    for code, name, prefixes in TAX_INDUSTRY_GROUPS
    for prefix in prefixes
}
_GROUP_BY_CODE = {code: (name, prefixes) for code, name, prefixes in TAX_INDUSTRY_GROUPS}
_GROUP_ORDER = {code: order for order, (code, _, _) in enumerate(TAX_INDUSTRY_GROUPS)}


def industry_group_for(code: str) -> tuple[str, str, int]:
    group_code, group_name = _GROUP_BY_PREFIX.get(code[:2], (code[:2], f"{code[:2]} 其他行業"))
    return group_code, group_name, _GROUP_ORDER.get(group_code, len(_GROUP_ORDER))


def industry_group_prefixes(code: str) -> tuple[str, ...] | None:
    group = _GROUP_BY_CODE.get(code)
    return group[1] if group else None
